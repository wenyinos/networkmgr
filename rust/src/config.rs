    #[test]
    fn psk_and_wep_field_order_matches_python() {
        let wpa2 = psk_network_fields("ExampleNet", "WPA2-PSK", "secret123").unwrap();
        assert_eq!(wpa2[0], ("ssid", r#"P"ExampleNet""#.to_string()));
        assert_eq!(wpa2[1], ("key_mgmt", "WPA-PSK".to_string()));
        assert_eq!(wpa2[2], ("proto", "RSN".to_string()));
        assert_eq!(wpa2[3], ("psk", "\"secret123\"".to_string()));

        let wpa3 = psk_network_fields("Net", "WPA3-SAE", "secret123").unwrap();
        assert_eq!(wpa3[2], ("proto", "RSN".to_string()));

        let wpa1 = psk_network_fields("Net", "WPA-PSK", "secret123").unwrap();
        assert_eq!(wpa1[2], ("proto", "WPA".to_string()));

        let wep = psk_network_fields("Net", "WEP", "0123456789").unwrap();
        assert_eq!(wep[1], ("key_mgmt", "NONE".to_string()));
        assert_eq!(wep[2], ("wep_tx_keyidx", "0".to_string()));
        assert_eq!(wep[3], ("wep_key0", "0123456789".to_string()));

        assert_eq!(
            psk_network_fields("Net", "WPA2-EAP", "x"),
            Err(ConfigError::UnsupportedSecurity("WPA2-EAP".to_string()))
        );
        assert_eq!(
            psk_network_fields("Net", "OPEN", "x"),
            Err(ConfigError::UnsupportedSecurity("OPEN".to_string()))
        );
    }

