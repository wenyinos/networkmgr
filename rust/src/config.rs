    #[test]
    fn eap_defaults_and_tls_branch() {
        let config = EapConfig {
            identity: "user@example.org".to_string(),
            password: "secret".to_string(),
            ..Default::default()
        };
        let fields = eap_network_fields("Corp", &config);
        assert_eq!(fields[1], ("key_mgmt", "WPA-EAP".to_string()));
        assert_eq!(fields[2], ("eap", "PEAP".to_string()));
        assert_eq!(fields[4], ("password", r#"P"secret""#.to_string()));
        assert_eq!(fields[5], ("phase2", r#"P"auth=MSCHAPV2""#.to_string()));
        assert_eq!(fields.len(), 6);

        let tls = EapConfig {
            eap_method: Some("TLS".to_string()),
            identity: "user".to_string(),
            client_cert: "/etc/ssl/client.pem".to_string(),
            private_key: "/etc/ssl/client.key".to_string(),
            ..Default::default()
        };
        let fields = eap_network_fields("Corp", &tls);
        let names: Vec<&str> = fields.iter().map(|(name, _)| *name).collect();
        assert_eq!(
            names,
            [
                "ssid",
                "key_mgmt",
                "eap",
                "identity",
                "client_cert",
                "private_key"
            ]
        );
        assert!(!names.contains(&"password"));
        assert!(!names.contains(&"phase2"));
    }

